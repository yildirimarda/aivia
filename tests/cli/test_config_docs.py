"""``aivia config docs`` contract: deterministic reference and staleness check."""

from __future__ import annotations

from pathlib import Path

import pytest
from pydantic import Field

from aivia.cli import main
from aivia.core.config import CORE_SECTION_KEYS, ConfigModel, SectionRegistry
from aivia.core.config.docs import (
    DOCS_TITLE,
    build_config_docs,
    docs_path,
    dump_config_docs,
    render_config_docs,
)


def run_docs(
    capsys: pytest.CaptureFixture[str],
    *extra: str,
) -> tuple[int, str, str]:
    code = main(["config", "docs", *extra])
    captured = capsys.readouterr()
    return code, captured.out, captured.err


def test_docs_print_every_registered_section_as_markdown(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys)

    assert code == 0
    assert err == ""
    assert output.startswith(f"# {DOCS_TITLE}")
    assert "<!-- Generated by `aivia config docs`" in output
    assert "## Root keys" in output
    for key in CORE_SECTION_KEYS:
        assert f"## `{key}`" in output
    assert "| `schema_version` | integer |" in output
    assert "## Type definitions" in output


def test_docs_take_section_descriptions_from_model_docstrings(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys)

    assert code == 0
    assert err == ""
    assert (
        "The ordered stages a pipeline runs and the timezone used for schedules."
        in output
    )
    assert "Alt text, subtitles and contrast settings for accessible outputs." in output


def test_docs_include_field_defaults_constraints_and_allowed_values(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys)

    assert code == 0
    assert err == ""
    assert "| `port` | integer | `8765` |" in output
    assert "| `min_contrast` | number | `4.5` | >= 1; <= 21 |" in output
    assert (
        '| `hashtag_style` | string | `"lower"` | '
        "one of: `lower`, `title`, `upper` |" in output
    )
    assert "Allowed values: `pause`, `downgrade`, `notify`." in output


def test_docs_output_is_byte_for_byte_deterministic(
    capsys: pytest.CaptureFixture[str],
) -> None:
    first_code, first, first_err = run_docs(capsys)
    second_code, second, second_err = run_docs(capsys)

    assert (first_code, first_err) == (0, "")
    assert (second_code, second_err) == (0, "")
    assert first == second
    assert first == dump_config_docs()


def test_docs_are_independent_of_registration_order() -> None:
    class AlphaConfig(ConfigModel):
        """Alpha section."""

        enabled: bool = True

    class ZuluConfig(ConfigModel):
        """Zulu section."""

        enabled: bool = True

    first = SectionRegistry()
    first.register("alpha", AlphaConfig)
    first.register("zulu", ZuluConfig)
    second = SectionRegistry()
    second.register("zulu", ZuluConfig)
    second.register("alpha", AlphaConfig)

    assert build_config_docs(first) == build_config_docs(second)


def test_docs_include_a_module_registered_section_and_field_description() -> None:
    class CustomConfig(ConfigModel):
        """A module section for testing."""

        enabled: bool = Field(
            default=True,
            description="Whether the custom module is enabled.",
        )

    sections = SectionRegistry()
    sections.register("custom", CustomConfig)

    text = build_config_docs(sections)

    assert "## `custom`" in text
    assert "A module section for testing." in text
    assert "Whether the custom module is enabled." in text


def test_render_uses_the_supplied_schema_only() -> None:
    schema = {
        "$defs": {
            "OnlyConfig": {
                "description": "A supplied schema.",
                "properties": {
                    "enabled": {"default": True, "type": "boolean"},
                },
                "type": "object",
            }
        },
        "properties": {
            "only": {
                "anyOf": [
                    {"$ref": "#/$defs/OnlyConfig"},
                    {"type": "null"},
                ]
            }
        },
        "type": "object",
    }

    text = render_config_docs(schema)

    assert "## `only`" in text
    assert "A supplied schema." in text
    assert "| `enabled` | boolean | `true` |" in text


def test_the_committed_reference_is_current() -> None:
    path = docs_path()

    assert path.is_file(), f"missing {path}"
    assert path.read_text(encoding="utf-8") == dump_config_docs(), (
        "configuration reference is stale; regenerate it with: "
        "aivia config docs --output docs/CONFIG.md"
    )


def test_docs_check_accepts_the_committed_copy(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys, "--check")

    assert code == 0
    assert err == ""
    assert "up to date" in output


def test_docs_check_fails_for_a_stale_file(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    stale = tmp_path / "CONFIG.md"
    stale.write_text("stale\n", encoding="utf-8")

    code, output, err = run_docs(capsys, "--check", "--output", str(stale))

    assert code == 1
    assert output == ""
    assert "stale" in err
    assert str(stale) in err


def test_docs_check_reports_a_missing_file_as_stale(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    missing = tmp_path / "missing" / "CONFIG.md"

    code, output, err = run_docs(capsys, "--check", "--output", str(missing))

    assert code == 1
    assert output == ""
    assert "stale" in err
    assert str(missing) in err


def test_docs_output_writes_the_generated_reference(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / "nested" / "CONFIG.md"

    code, output, err = run_docs(capsys, "--output", str(target))

    assert code == 0
    assert err == ""
    assert str(target) in output
    assert target.read_text(encoding="utf-8") == dump_config_docs()
