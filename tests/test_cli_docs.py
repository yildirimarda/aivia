"""``aivia docs``: deterministic CLI reference and staleness check."""

from __future__ import annotations

from pathlib import Path

import pytest

from aivia.cli import Command, CommandRegistry, main
from aivia.cli.docs import (
    DOCS_TITLE,
    build_cli_docs,
    docs_path,
    dump_cli_docs,
    render_cli_docs,
)


def run_docs(
    capsys: pytest.CaptureFixture[str],
    *extra: str,
) -> tuple[int, str, str]:
    code = main(["docs", *extra])
    captured = capsys.readouterr()
    return code, captured.out, captured.err


def _registry() -> CommandRegistry:
    registry = CommandRegistry()
    registry.register(Command(name="alpha", handler=lambda _: 0, help="Alpha command."))
    registry.register(Command(name="zulu", handler=lambda _: 0, help="Zulu command."))
    return registry


def _command_with_argument() -> CommandRegistry:
    registry = CommandRegistry()

    def configure(parser) -> None:
        parser.add_argument("--count", type=int, default=3, help="How many times.")

    registry.register(
        Command(
            name="repeat",
            handler=lambda _: 0,
            help="Repeat something.",
            configure=configure,
        )
    )
    return registry


def test_docs_render_every_registered_command() -> None:
    text = build_cli_docs(_registry())

    assert text.startswith(f"# {DOCS_TITLE}")
    assert "<!-- Generated by `aivia docs`" in text
    assert "## Commands" in text
    assert "| `alpha` | Alpha command. |" in text
    assert "| `zulu` | Zulu command. |" in text
    assert text.index("alpha") < text.index("zulu")


def test_docs_include_command_help_and_arguments() -> None:
    text = build_cli_docs(_command_with_argument())

    assert "## `repeat`" in text
    assert "Repeat something." in text
    assert "| `--count` | integer | `3` | How many times. |" in text


def test_docs_output_is_byte_for_byte_deterministic() -> None:
    first = build_cli_docs(_registry())
    second = build_cli_docs(_registry())

    assert first == second
    assert first == dump_cli_docs(_registry())


def test_docs_are_independent_of_registration_order() -> None:
    first = CommandRegistry()
    first.register(Command(name="alpha", handler=lambda _: 0, help="Alpha command."))
    first.register(Command(name="zulu", handler=lambda _: 0, help="Zulu command."))
    second = CommandRegistry()
    second.register(Command(name="zulu", handler=lambda _: 0, help="Zulu command."))
    second.register(Command(name="alpha", handler=lambda _: 0, help="Alpha command."))

    assert build_cli_docs(first) == build_cli_docs(second)


def test_render_uses_the_supplied_registry_only() -> None:
    text = render_cli_docs(_command_with_argument())

    assert "## `repeat`" in text
    assert "## `config`" not in text
    assert "## `docs`" not in text


def test_the_committed_reference_is_current() -> None:
    path = docs_path()

    assert path.is_file(), f"missing {path}"
    assert path.read_text(encoding="utf-8") == dump_cli_docs(), (
        "CLI reference is stale; regenerate it with: aivia docs --output docs/CLI.md"
    )


def test_docs_print_the_generated_reference(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys)

    assert code == 0
    assert err == ""
    assert output == dump_cli_docs()


def test_docs_check_accepts_the_committed_copy(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys, "--check")

    assert code == 0
    assert err == ""
    assert "up to date" in output


def test_docs_check_fails_for_a_stale_file(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    stale = tmp_path / "CLI.md"
    stale.write_text("stale\n", encoding="utf-8")

    code, output, err = run_docs(capsys, "--check", "--output", str(stale))

    assert code == 1
    assert output == ""
    assert "stale" in err
    assert str(stale) in err


def test_docs_check_reports_a_missing_file_as_stale(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    missing = tmp_path / "missing" / "CLI.md"

    code, output, err = run_docs(capsys, "--check", "--output", str(missing))

    assert code == 1
    assert output == ""
    assert "stale" in err
    assert str(missing) in err


def test_docs_output_writes_the_generated_reference(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / "nested" / "CLI.md"

    code, output, err = run_docs(capsys, "--output", str(target))

    assert code == 0
    assert err == ""
    assert str(target) in output
    assert target.read_text(encoding="utf-8") == dump_cli_docs()
