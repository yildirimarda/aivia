"""Provider capability matrix: deterministic reference and staleness check."""

from __future__ import annotations

from pathlib import Path

import pytest

from aivia.cli import main
from aivia.core import paths
from aivia.core.models import AssetLicense, ProviderMeta, ProviderPrice, RateLimit
from aivia.providers import Provider, ProviderRegistry
from aivia.providers.docs import (
    DOCS_TITLE,
    build_provider_docs,
    docs_path,
    dump_provider_docs,
    render_provider_docs,
)


class _AlphaProvider(Provider):
    default_metadata = ProviderMeta(
        name="alpha",
        capabilities=["llm", "tts"],
        supported_options={"llm": ["fast", "smart"]},
        pricing={
            "llm": ProviderPrice(amount_usd=0.002, unit="1k_tokens"),
            "tts": ProviderPrice(amount_usd=0.01, unit="1k_chars"),
        },
        rate_limit=RateLimit(requests_per_minute=120, burst=10),
        quality_rank=2,
        license=AssetLicense(name="proprietary", commercial_use=True),
        commercial_use_notes="Read the terms before publishing.",
    )


class _ZuluProvider(Provider):
    default_metadata = ProviderMeta(
        name="zulu",
        capabilities=["image_gen"],
        pricing={"image_gen": ProviderPrice(amount_usd=0.04, unit="image")},
        rate_limit=RateLimit(requests_per_minute=0),
        license=AssetLicense(name="CC0"),
    )


def _registry() -> ProviderRegistry:
    registry = ProviderRegistry()
    registry.register("alpha", _AlphaProvider)
    registry.register("zulu", _ZuluProvider)
    return registry


def run_docs(
    capsys: pytest.CaptureFixture[str],
    *extra: str,
) -> tuple[int, str, str]:
    code = main(["providers", "docs", *extra])
    captured = capsys.readouterr()
    return code, captured.out, captured.err


def test_docs_render_the_capability_matrix_from_provider_metadata() -> None:
    text = build_provider_docs(_registry())

    assert text.startswith(f"# {DOCS_TITLE}")
    assert "<!-- Generated by `aivia providers docs`" in text
    assert "## Capability matrix" in text
    assert (
        "| `alpha` | `llm`, `tts` | 120/min, burst 10 | 2 | proprietary | yes |" in text
    )
    assert "| `zulu` | `image_gen` | unlimited | - | CC0 | unknown |" in text


def test_docs_render_prices_options_and_licensing_notes() -> None:
    text = build_provider_docs(_registry())

    assert "| `alpha` | `llm` | $0.002 per 1k_tokens |" in text
    assert "| `alpha` | `tts` | $0.01 per 1k_chars |" in text
    assert "| `alpha` | `llm` | `fast`, `smart` |" in text
    assert "Read the terms before publishing." in text
    assert "| `alpha` | proprietary | yes | no |" in text


def test_docs_output_is_byte_for_byte_deterministic() -> None:
    first = build_provider_docs(_registry())
    second = build_provider_docs(_registry())

    assert first == second
    assert first == dump_provider_docs(_registry())


def test_docs_are_independent_of_registration_order() -> None:
    first = ProviderRegistry()
    first.register("alpha", _AlphaProvider)
    first.register("zulu", _ZuluProvider)
    second = ProviderRegistry()
    second.register("zulu", _ZuluProvider)
    second.register("alpha", _AlphaProvider)

    assert build_provider_docs(first) == build_provider_docs(second)


def test_render_uses_the_supplied_metadata_only() -> None:
    metadata = ProviderMeta(
        name="only",
        capabilities=["search"],
        pricing={"search": ProviderPrice(amount_usd=0.001, unit="query")},
    )

    text = render_provider_docs({"only": metadata})

    assert "| `only` | `search` |" in text
    assert "| `only` | `search` | $0.001 per query |" in text
    assert "alpha" not in text


def test_a_provider_without_static_metadata_is_still_listed() -> None:
    class _Opaque(Provider):
        def __init__(self) -> None:
            super().__init__()

    registry = ProviderRegistry()
    registry.register("opaque", _Opaque)

    text = build_provider_docs(registry)

    assert "| `opaque` | - | 60/min | - | - | unknown |" in text


def test_the_committed_reference_is_current() -> None:
    path = docs_path()

    assert path.is_file(), f"missing {path}"
    assert path.read_text(encoding="utf-8") == dump_provider_docs(), (
        "provider reference is stale; regenerate it with: "
        "aivia providers docs --output docs/PROVIDERS.md"
    )


def test_local_background_removal_and_remote_ops_adapters_are_in_the_matrix() -> None:
    text = dump_provider_docs()

    for name in ("local-background-removal", "local-rembg"):
        assert f"| `{name}` | `image_edit` | 60/min | - | - | unknown |" in text
        assert f"| `{name}` | `image_edit` | $0 per image |" in text
        assert f"| `{name}` | - | - |" in text

    for name in (
        "remote-ops",
        "remote_ops",
        "remote-image-ops",
        "remote_image_ops",
        "remote-image-edit",
        "remote-background-removal",
        "remote-upscale",
    ):
        assert f"| `{name}` | `image_edit` | 60/min | - | - | unknown |" in text
        assert f"| `{name}` | - | - |" in text


def test_docs_print_the_generated_reference(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys)

    assert code == 0
    assert err == ""
    assert output == dump_provider_docs()


def test_docs_check_accepts_the_committed_copy(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys, "--check")

    assert code == 0
    assert err == ""
    assert "up to date" in output


def test_docs_check_fails_for_a_stale_file(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    stale = tmp_path / "PROVIDERS.md"
    stale.write_text("stale\n", encoding="utf-8")

    code, output, err = run_docs(capsys, "--check", "--output", str(stale))

    assert code == 1
    assert output == ""
    assert "stale" in err
    assert str(stale) in err


def test_docs_check_reports_a_missing_file_as_stale(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    missing = tmp_path / "missing" / "PROVIDERS.md"

    code, output, err = run_docs(capsys, "--check", "--output", str(missing))

    assert code == 1
    assert output == ""
    assert "stale" in err
    assert str(missing) in err


def test_docs_output_writes_the_generated_reference(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / "nested" / "PROVIDERS.md"

    code, output, err = run_docs(capsys, "--output", str(target))

    assert code == 0
    assert err == ""
    assert str(target) in output
    assert target.read_text(encoding="utf-8") == dump_provider_docs()


def test_cli_docs_bootstraps_into_the_isolated_config_not_the_host_home(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """``providers docs`` bootstraps into the isolated config dir, never home."""
    config_dir = paths.config_dir()
    assert config_dir == tmp_path / "config" / "aivia"

    code, output, err = run_docs(capsys)

    assert code == 0
    assert err == ""
    assert output == dump_provider_docs()
    assert (config_dir / "config.yaml").is_file()
