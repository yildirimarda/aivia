"""Platform onboarding document: deterministic reference and staleness check."""

from __future__ import annotations

from pathlib import Path

import pytest

from aivia.cli import main
from aivia.core.platforms import (
    CaptionLimits,
    DisclosureRules,
    DurationLimits,
    MediaLimits,
    MediaLimitsCollection,
    Platform,
    PlatformCatalog,
    load_platforms,
)
from aivia.publish.docs import (
    DOCS_TITLE,
    build_platform_docs,
    docs_path,
    dump_platform_docs,
    render_platform_docs,
)


def _platform(
    platform_id: str,
    name: str,
    *,
    media_types: tuple[str, ...] = ("video",),
    max_seconds: float | None = None,
    max_file_size_bytes: int | None = None,
    max_length: int | None = None,
    max_hashtags: int | None = None,
    disclosure_required: bool = True,
) -> Platform:
    limits: dict[str, MediaLimits] = {}
    for media_type in media_types:
        limits[media_type] = MediaLimits(
            media_type=media_type,
            duration=DurationLimits(max_seconds=max_seconds),
            resolutions=("1080x1920",),
            aspect_ratios=("9:16",),
            max_file_size_bytes=max_file_size_bytes,
        )
    return Platform(
        id=platform_id,
        name=name,
        media_types=media_types,
        limits=MediaLimitsCollection(limits),
        caption_limits=CaptionLimits(max_length=max_length, max_hashtags=max_hashtags),
        disclosure=DisclosureRules(required=disclosure_required),
    )


def _catalog(*platforms: Platform) -> PlatformCatalog:
    return PlatformCatalog(platforms)


def run_docs(
    capsys: pytest.CaptureFixture[str],
    *extra: str,
) -> tuple[int, str, str]:
    code = main(["publish", "docs", *extra])
    captured = capsys.readouterr()
    return code, captured.out, captured.err


def test_docs_render_the_platforms_from_the_catalog() -> None:
    catalog = _catalog(_platform("youtube", "YouTube Shorts"))
    text = build_platform_docs(catalog)

    assert text.startswith(f"# {DOCS_TITLE}")
    assert "<!-- Generated by `aivia publish docs`" in text
    assert "## Apps" in text
    assert "`youtube`" in text
    assert "YouTube Shorts" in text
    assert "`video`" in text


def test_docs_cover_all_six_topics() -> None:
    catalog = load_platforms()
    text = build_platform_docs(catalog)

    assert "## Apps" in text
    assert "## Scopes" in text
    assert "## Account types" in text
    assert "## Audits" in text
    assert "## Quota requests" in text
    assert "## Environment variables" in text


def test_docs_list_every_default_platform() -> None:
    catalog = load_platforms()
    text = build_platform_docs(catalog)

    for platform_id in catalog.ids():
        assert f"`{platform_id}`" in text


def test_docs_output_is_byte_for_byte_deterministic() -> None:
    catalog = load_platforms()
    first = build_platform_docs(catalog)
    second = build_platform_docs(catalog)

    assert first == second
    assert first == dump_platform_docs(catalog)


def test_docs_are_independent_of_catalog_order() -> None:
    alpha = _platform("alpha", "Alpha")
    zulu = _platform("zulu", "Zulu")
    first = _catalog(alpha, zulu)
    second = _catalog(zulu, alpha)

    assert build_platform_docs(first) == build_platform_docs(second)


def test_render_uses_the_supplied_catalog_only() -> None:
    only = _catalog(_platform("only", "Only"))
    text = render_platform_docs(only)

    assert "`only`" in text
    assert "Only" in text
    assert "| `only` |" in text
    assert "| `youtube` |" not in text


def test_the_committed_reference_is_current() -> None:
    path = docs_path()

    assert path.is_file(), f"missing {path}"
    assert path.read_text(encoding="utf-8") == dump_platform_docs(), (
        "platform onboarding document is stale; regenerate it with: "
        "aivia publish docs --output docs/PLATFORMS.md"
    )


def test_docs_print_the_generated_reference(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys)

    assert code == 0
    assert err == ""
    assert output == dump_platform_docs()


def test_docs_check_accepts_the_committed_copy(
    capsys: pytest.CaptureFixture[str],
) -> None:
    code, output, err = run_docs(capsys, "--check")

    assert code == 0
    assert err == ""
    assert "up to date" in output


def test_docs_check_fails_for_a_stale_file(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    stale = tmp_path / "PLATFORMS.md"
    stale.write_text("stale\n", encoding="utf-8")

    code, output, err = run_docs(capsys, "--check", "--output", str(stale))

    assert code == 1
    assert output == ""
    assert "stale" in err
    assert str(stale) in err


def test_docs_check_reports_a_missing_file_as_stale(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    missing = tmp_path / "missing" / "PLATFORMS.md"

    code, output, err = run_docs(capsys, "--check", "--output", str(missing))

    assert code == 1
    assert output == ""
    assert "stale" in err
    assert str(missing) in err


def test_docs_output_writes_the_generated_reference(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / "nested" / "PLATFORMS.md"

    code, output, err = run_docs(capsys, "--output", str(target))

    assert code == 0
    assert err == ""
    assert str(target) in output
    assert target.read_text(encoding="utf-8") == dump_platform_docs()
