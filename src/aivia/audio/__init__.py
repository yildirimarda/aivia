"""Voice synthesis, subtitles, quality checks, timeline building and stages.

The package owns the voice stage that turns written scripts into measured
speech and a timeline file, the subtitle stage that turns that timeline into
one styled ASS file per language, the music stage that selects a licensed bed
and marks it for ducking, the sound effect stage that places rule matched
effects with a gain, and the deterministic audio quality checks that read the
resulting segments. It consumes the core script model, the compose timeline
schema and the media services; it does not select providers or write cost
events itself.
"""

