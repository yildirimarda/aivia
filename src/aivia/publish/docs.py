"""Deterministic Markdown onboarding guide for publishing to platforms.

The document covers the six things a new publisher needs to know before
content reaches a platform: the apps you can publish to, the scopes each
account needs, the account types AIVIA supports, the audit trail every
publish leaves, the quota request checked before a post is sent, and the
environment variables that hold credentials. Platform limits are read from
the packaged ``platforms.yaml`` data file so the guide stays in sync with
the rules code enforces.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from aivia.core.platforms import (
    CaptionLimits,
    Platform,
    PlatformCatalog,
    load_platforms,
)

__all__ = [
    "DOCS_FILENAME",
    "DOCS_TITLE",
    "build_platform_docs",
    "docs_path",
    "dump_platform_docs",
    "render_platform_docs",
]

DOCS_FILENAME = "PLATFORMS.md"
DOCS_TITLE = "AIVIA platform onboarding"

_GENERATED_NOTICE = (
    "<!-- Generated by `aivia publish docs`; do not edit by hand. -->\n"
    "<!-- Regenerate: aivia publish docs --output docs/PLATFORMS.md -->\n"
)

_PREAMBLE = (
    "This guide walks a new publisher through the six things that must be "
    "true before content reaches a platform: the apps you can publish to, "
    "the scopes each account needs, the account types AIVIA supports, the "
    "audit trail every publish leaves, the quota request checked before a "
    "post is sent, and the environment variables that hold credentials. "
    "Platform limits are read from the packaged ``platforms.yaml`` data "
    "file, so this document stays in sync with the rules code enforces. "
    "No provider or network call is made while generating it."
)


def build_platform_docs(catalog: PlatformCatalog | None = None) -> str:
    """Return the Markdown onboarding guide for *catalog*.

    When *catalog* is ``None`` the packaged default platform data is loaded,
    which is what the committed ``docs/PLATFORMS.md`` is generated from.
    """
    source = load_platforms() if catalog is None else catalog
    return render_platform_docs(source)


def dump_platform_docs(catalog: PlatformCatalog | None = None) -> str:
    """Alias for :func:`build_platform_docs`, mirroring ``dump_config_docs``."""
    return build_platform_docs(catalog)


def docs_path(root: Path | None = None) -> Path:
    """Return the path of the committed reference, ``docs/PLATFORMS.md``.

    Without an explicit *root*, the repository root is found by walking up
    from this module so the command works from any working directory. An
    installed wheel has no repository, so the current directory is used
    instead.
    """
    if root is not None:
        return Path(root) / "docs" / DOCS_FILENAME
    for parent in Path(__file__).resolve().parents:
        if (parent / "docs" / "DESIGN.md").is_file():
            return parent / "docs" / DOCS_FILENAME
    return Path.cwd() / "docs" / DOCS_FILENAME


def render_platform_docs(catalog: PlatformCatalog) -> str:
    """Render *catalog* as stable Markdown text."""
    lines: list[str] = [
        f"# {DOCS_TITLE}",
        "",
        _GENERATED_NOTICE,
        _PREAMBLE,
        "",
        "## Apps",
        "",
        "AIVIA publishes to the apps below. Each app declares the media types it "
        "accepts and the limits every output must meet before it can be posted. "
        "Limits come from ``platforms.yaml`` and are enforced by output "
        "validation, not by convention.",
        "",
        "| App | Name | Media types | Duration | Resolution | "
        "Max file | Caption | Hashtags | Disclosure |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for platform_id in catalog.ids():
        platform = catalog[platform_id]
        lines.append(_app_row(platform))
    lines.append("")

    lines.extend(
        [
            "## Scopes",
            "",
            "A scope is the permission an account holds on a platform -- for "
            "example the right to post, upload media or read insights. AIVIA "
            "only publishes through a provider that declares the ``publish`` "
            "capability for the target app, and ``aivia publish check`` "
            "verifies that scope before any request is sent. An account "
            "without the required scope cannot publish, and attempting to do "
            "so fails fast with a clear message instead of a silent drop.",
            "",
        ]
    )

    lines.extend(
        [
            "## Account types",
            "",
            "An account is identified by ``platform/language`` -- for example "
            "``youtube/en`` or ``tiktok/de`` -- and is bound to exactly one "
            "platform and one language. An account can be a personal profile "
            "or a business page; AIVIA does not distinguish between them in "
            "config, so the account type is whatever the connected credential "
            "represents. Each account lists the credential references it "
            "resolves to (for example an OAuth token or an API key). An "
            "account can be disabled without deleting it, which stops "
            "publishing to it while keeping its history.",
            "",
        ]
    )

    lines.extend(
        [
            "## Audits",
            "",
            "Every publish is recorded in an append-only audit trail keyed by "
            "an idempotency key. The trail stores the platform, account, "
            "profile, language, format, caption, media, visibility, remote "
            "identifier and the platform-assigned URL, plus whether the post "
            "is a dry run. A repeat attempt with the same idempotency key "
            "returns the stored result instead of posting again, so a retry "
            "after a timeout can never double post. Only retryable failures "
            "are retried; permanent errors such as an auth or invalid request "
            "error are surfaced immediately. A publish attestation records "
            "who confirmed rights and disclosure, when, the applied disclosure "
            "text and the license summary, and strict mode blocks publishing "
            "when anything is missing.",
            "",
        ]
    )

    lines.extend(
        [
            "## Quota requests",
            "",
            "Before a publish is sent, ``aivia publish check`` runs a quota "
            "request against the configured budget: the estimated cost is "
            "checked against the remaining day, month and per-provider limits "
            "and the request is rejected when it would exceed a cap. Budget "
            "checks reserve the estimate atomically so concurrent calls cannot "
            "both pass the same cap, and on exceeding a limit the run can be "
            "downgraded to a cheaper provider, paused as paused budget, or "
            "notify only. Quota state is persisted so a restart does not "
            "repeat an alert within the same period.",
            "",
        ]
    )

    lines.extend(
        [
            "## Environment variables",
            "",
            "Credentials live in environment variables, never in config files. "
            "A secret reference such as ``OPENAI_API_KEY`` is resolved as "
            "``AIVA_OPENAI_API_KEY`` from the environment, then from the "
            "``secrets.env`` file beside the config, then from the OS keyring. "
            "The lookup order is environment, secrets file, keyring. Values "
            "are never included in errors or log messages, and resolved "
            "config, run snapshots and sidecars are masked so secrets never "
            "leak to disk. The ``TOKEN_STORE_KEY`` reference "
            "(``AIVA_TOKEN_STORE_KEY``) encrypts stored publish tokens and "
            "must be set before publishing.",
            "",
        ]
    )

    return "\n".join(lines).rstrip() + "\n"


def _app_row(platform: Platform) -> str:
    return (
        f"| `{platform.id}` | {_cell(platform.display_name)} | "
        f"{_media_types(platform)} | {_duration(platform)} | "
        f"{_resolution(platform)} | {_max_file(platform)} | "
        f"{_caption(platform)} | {_hashtags(platform)} | "
        f"{_disclosure(platform)} |"
    )


def _media_types(platform: Platform) -> str:
    if not platform.media_types:
        return "-"
    return ", ".join(f"`{t}`" for t in platform.media_types)


def _duration(platform: Platform) -> str:
    duration = platform.limits.primary.duration
    parts: list[str] = []
    if duration.min_seconds is not None:
        parts.append(f"{_seconds(duration.min_seconds)} min")
    if duration.max_seconds is not None:
        parts.append(f"{_seconds(duration.max_seconds)} max")
    if not parts:
        return "-"
    return " - ".join(parts)


def _seconds(value: float) -> str:
    if value == int(value):
        return f"{int(value)}s"
    return f"{value:g}s"


def _resolution(platform: Platform) -> str:
    resolutions = platform.limits.primary.resolutions
    ratios = platform.limits.primary.aspect_ratios
    if not resolutions:
        return "-"
    cells = [f"`{r}`" for r in resolutions]
    if ratios:
        cells = [
            f"{cell} ({ratio})" for cell, ratio in zip(cells, ratios, strict=False)
        ]
    return ", ".join(cells)


def _max_file(platform: Platform) -> str:
    size = platform.limits.primary.max_file_size_bytes
    if size is None:
        return "-"
    return _bytes(size)


def _caption(platform: Platform) -> str:
    limits: CaptionLimits = platform.caption_limits
    if limits.max_length is None:
        return "-"
    return str(limits.max_length)


def _hashtags(platform: Platform) -> str:
    value = platform.caption_limits.max_hashtags
    return "-" if value is None else str(value)


def _disclosure(platform: Platform) -> str:
    return "yes" if platform.disclosure.required else "no"


def _bytes(value: int) -> str:
    units = [
        (1 << 40, "TB"),
        (1 << 30, "GB"),
        (1 << 20, "MB"),
        (1 << 10, "kB"),
        (1, "B"),
    ]
    for divisor, unit in units:
        if value >= divisor:
            amount = value / divisor
            if amount == int(amount):
                return f"{int(amount)} {unit}"
            return f"{amount:g} {unit}"
    return f"{value} B"


def _cell(value: Any) -> str:
    return " ".join(str(value).split()).replace("|", "\\|")
