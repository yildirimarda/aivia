"""Deterministic Markdown reference for the registered configuration sections.

The document is rendered from the same JSON Schema that ``aivia config schema``
exports. Model docstrings become section and type descriptions, field titles
become key names and JSON Schema constraints become the constraint column, so
the reference cannot drift from the models. The committed copy is compared
byte for byte, which makes a stale reference fail the test suite.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from aivia.core.config.registry import SectionRegistry
from aivia.core.config.schema import build_config_schema

__all__ = [
    "DOCS_FILENAME",
    "DOCS_TITLE",
    "build_config_docs",
    "docs_path",
    "dump_config_docs",
    "render_config_docs",
]

DOCS_FILENAME = "CONFIG.md"
DOCS_TITLE = "AIVIA configuration reference"

_GENERATED_NOTICE = (
    "<!-- Generated by `aivia config docs`; do not edit by hand. -->\n"
    "<!-- Regenerate: aivia config docs --output docs/CONFIG.md -->\n"
)

_PREAMBLE = (
    "This reference is generated from the registered configuration models, "
    "their JSON Schema and model docstrings. Every top-level key is one "
    "section; unknown keys are rejected. Values may reference environment "
    "variables as `${NAME}` or `${NAME:-default}`."
)

_TYPE_KEYS = ("anyOf", "oneOf", "allOf")


def build_config_docs(sections: SectionRegistry | None = None) -> str:
    """Return the Markdown reference for every section in *sections*."""
    return render_config_docs(build_config_schema(sections))


def dump_config_docs(sections: SectionRegistry | None = None) -> str:
    """Alias for :func:`build_config_docs`, mirroring ``dump_config_schema``."""
    return build_config_docs(sections)


def render_config_docs(schema: Mapping[str, Any]) -> str:
    """Render *schema* as stable Markdown text."""
    definitions = _definitions(schema)
    root = _properties(schema)
    anchors = _section_anchors(root, definitions)

    lines = [
        f"# {DOCS_TITLE}",
        "",
        _GENERATED_NOTICE,
        _PREAMBLE,
        "",
        "## Root keys",
        "",
        *_root_table(root, definitions, anchors),
    ]

    for key in sorted(root):
        lines.extend(_render_section(key, root[key], definitions, anchors))

    nested = sorted(set(definitions) - set(anchors))
    if nested:
        lines.extend(["## Type definitions", ""])
        for name in nested:
            lines.extend(
                _render_definition(name, definitions[name], definitions, anchors)
            )

    return "\n".join(lines).rstrip() + "\n"


def docs_path(root: Path | None = None) -> Path:
    """Return the path of the committed reference, ``docs/CONFIG.md``.

    Without an explicit *root*, the repository root is found by walking up from
    this module so the command works from any working directory. An installed
    wheel has no repository, so the current directory is used instead.
    """
    if root is not None:
        return Path(root) / "docs" / DOCS_FILENAME
    for parent in Path(__file__).resolve().parents:
        if (parent / "docs" / "DESIGN.md").is_file():
            return parent / "docs" / DOCS_FILENAME
    return Path.cwd() / "docs" / DOCS_FILENAME


def _definitions(schema: Mapping[str, Any]) -> dict[str, Mapping[str, Any]]:
    raw = schema.get("$defs")
    if not isinstance(raw, Mapping):
        return {}
    return {
        str(name): value for name, value in raw.items() if isinstance(value, Mapping)
    }


def _properties(schema: Mapping[str, Any]) -> dict[str, Mapping[str, Any]]:
    raw = schema.get("properties")
    if not isinstance(raw, Mapping):
        return {}
    return {
        str(name): value for name, value in raw.items() if isinstance(value, Mapping)
    }


def _ref_name(schema: Mapping[str, Any]) -> str | None:
    ref = schema.get("$ref")
    if isinstance(ref, str) and ref.startswith("#/$defs/"):
        return ref.rsplit("/", 1)[-1]
    return None


def _find_ref(schema: Mapping[str, Any]) -> str | None:
    name = _ref_name(schema)
    if name is not None:
        return name
    for key in _TYPE_KEYS:
        entries = schema.get(key)
        if not isinstance(entries, Sequence) or isinstance(entries, (str, bytes)):
            continue
        for entry in entries:
            if isinstance(entry, Mapping):
                name = _find_ref(entry)
                if name is not None:
                    return name
    return None


def _section_anchors(
    root: Mapping[str, Mapping[str, Any]],
    definitions: Mapping[str, Mapping[str, Any]],
) -> dict[str, str]:
    anchors: dict[str, str] = {}
    for key, prop in root.items():
        name = _find_ref(prop)
        if name is not None and name in definitions:
            anchors.setdefault(name, key)
    return anchors


def _anchor(name: str) -> str:
    return name.lower()


def _clean(text: str) -> str:
    return " ".join(text.split())


def _describe(
    schema: Mapping[str, Any],
    definitions: Mapping[str, Mapping[str, Any]],
) -> str:
    description = schema.get("description")
    if isinstance(description, str) and description.strip():
        return _clean(description)
    name = _find_ref(schema)
    if name is not None and name in definitions:
        description = definitions[name].get("description")
        if isinstance(description, str) and description.strip():
            return _clean(description)
    return ""


def _format_type(
    schema: Mapping[str, Any],
    definitions: Mapping[str, Mapping[str, Any]],
    anchors: Mapping[str, str],
) -> str:
    name = _ref_name(schema)
    if name is not None:
        target = anchors.get(name, _anchor(name))
        return f"[{name}](#{target})"

    for key in _TYPE_KEYS:
        entries = schema.get(key)
        if not isinstance(entries, Sequence) or isinstance(entries, (str, bytes)):
            continue
        rendered: list[str] = []
        for entry in entries:
            if not isinstance(entry, Mapping):
                continue
            text = _format_type(entry, definitions, anchors)
            if text not in rendered:
                rendered.append(text)
        if rendered:
            return " or ".join(rendered)

    kind = schema.get("type")
    if kind == "array":
        items = schema.get("items")
        if isinstance(items, Mapping):
            return f"array of {_format_type(items, definitions, anchors)}"
        return "array"
    if kind == "object":
        additional = schema.get("additionalProperties")
        if isinstance(additional, Mapping):
            return f"map of {_format_type(additional, definitions, anchors)}"
        return "object"
    if isinstance(kind, str):
        return kind
    if "const" in schema:
        return "constant"
    return "any"


def _format_default(schema: Mapping[str, Any]) -> str:
    if "default" not in schema:
        return ""
    value = json.dumps(schema["default"], ensure_ascii=False, sort_keys=True)
    return f"`{value}`"


def _format_constraints(
    schema: Mapping[str, Any],
    definitions: Mapping[str, Mapping[str, Any]],
    seen: frozenset[str] = frozenset(),
) -> str:
    items: list[str] = []

    name = _ref_name(schema)
    if name is not None and name in definitions and name not in seen:
        nested = _format_constraints(
            definitions[name],
            definitions,
            seen | {name},
        )
        if nested:
            items.extend(part for part in nested.split("; ") if part)

    if "const" in schema:
        value = json.dumps(schema["const"], ensure_ascii=False, sort_keys=True)
        items.append(f"= `{value}`")
    enum = schema.get("enum")
    if isinstance(enum, Sequence) and not isinstance(enum, (str, bytes)):
        values = ", ".join(f"`{value}`" for value in enum)
        items.append(f"one of: {values}")
    if "minimum" in schema:
        items.append(f">= {schema['minimum']}")
    if "maximum" in schema:
        items.append(f"<= {schema['maximum']}")
    if "exclusiveMinimum" in schema:
        items.append(f"> {schema['exclusiveMinimum']}")
    if "exclusiveMaximum" in schema:
        items.append(f"< {schema['exclusiveMaximum']}")
    if "minLength" in schema:
        items.append(f"length >= {schema['minLength']}")
    if "maxLength" in schema:
        items.append(f"length <= {schema['maxLength']}")
    if "pattern" in schema:
        items.append(f"pattern `{schema['pattern']}`")
    if "minItems" in schema:
        items.append(f"items >= {schema['minItems']}")
    if "maxItems" in schema:
        items.append(f"items <= {schema['maxItems']}")
    if schema.get("uniqueItems") is True:
        items.append("unique items")

    for key in _TYPE_KEYS:
        entries = schema.get(key)
        if not isinstance(entries, Sequence) or isinstance(entries, (str, bytes)):
            continue
        for entry in entries:
            if not isinstance(entry, Mapping) or entry.get("type") == "null":
                continue
            nested = _format_constraints(entry, definitions, seen)
            for part in nested.split("; "):
                if part and part not in items:
                    items.append(part)

    return "; ".join(items)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _row(cells: Sequence[str]) -> str:
    return "| " + " | ".join(_cell(cell) for cell in cells) + " |"


def _root_table(
    root: Mapping[str, Mapping[str, Any]],
    definitions: Mapping[str, Mapping[str, Any]],
    anchors: Mapping[str, str],
) -> list[str]:
    rows: list[tuple[str, str, str]] = [
        ("`schema_version`", "integer", "Configuration schema version.")
    ]
    for key in sorted(root):
        if key == "schema_version":
            continue
        prop = root[key]
        rows.append(
            (
                f"`{key}`",
                _format_type(prop, definitions, anchors),
                _describe(prop, definitions),
            )
        )

    lines = ["| Key | Type | Description |", "| --- | --- | --- |"]
    lines.extend(_row(row) for row in rows)
    lines.append("")
    return lines


def _render_section(
    key: str,
    prop: Mapping[str, Any],
    definitions: Mapping[str, Mapping[str, Any]],
    anchors: Mapping[str, str],
) -> list[str]:
    lines = [f"## `{key}`", ""]
    description = _describe(prop, definitions)
    if description:
        lines.extend([description, ""])

    target = _find_ref(prop)
    fields = (
        _properties(definitions[target])
        if target is not None and target in definitions
        else _properties(prop)
    )
    if fields:
        lines.extend(_field_table(fields, definitions, anchors))
    else:
        lines.extend([f"Type: {_format_type(prop, definitions, anchors)}", ""])
    return lines


def _render_definition(
    name: str,
    definition: Mapping[str, Any],
    definitions: Mapping[str, Mapping[str, Any]],
    anchors: Mapping[str, str],
) -> list[str]:
    lines = [f"### {name}", ""]
    description = _describe(definition, definitions)
    if description:
        lines.extend([description, ""])

    enum = definition.get("enum")
    if isinstance(enum, Sequence) and not isinstance(enum, (str, bytes)):
        values = ", ".join(f"`{value}`" for value in enum)
        lines.extend([f"Allowed values: {values}.", ""])
        return lines

    fields = _properties(definition)
    if fields:
        lines.extend(_field_table(fields, definitions, anchors))
    else:
        lines.extend(["This type has no configurable keys.", ""])
    return lines


def _field_table(
    fields: Mapping[str, Mapping[str, Any]],
    definitions: Mapping[str, Mapping[str, Any]],
    anchors: Mapping[str, str],
) -> list[str]:
    lines = [
        "| Key | Type | Default | Constraints | Description |",
        "| --- | --- | --- | --- | --- |",
    ]
    for key in sorted(fields):
        prop = fields[key]
        lines.append(
            _row(
                (
                    f"`{key}`",
                    _format_type(prop, definitions, anchors),
                    _format_default(prop),
                    _format_constraints(prop, definitions),
                    _describe(prop, definitions),
                )
            )
        )
    lines.append("")
    return lines
