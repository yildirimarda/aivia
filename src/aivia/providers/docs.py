def build_provider_docs(registry: ProviderRegistry | None = None) -> str:
    """Return the Markdown matrix for every provider in *registry*."""
    _load_builtin_adapters()
    source = provider_registry if registry is None else registry
    entries: dict[str, ProviderMeta] = {}
    for registration in source.registrations():
        metadata = static_metadata(registration.provider)
        entries[registration.name] = metadata or ProviderMeta(name=registration.name)
    return render_provider_docs(entries)


def dump_provider_docs(registry: ProviderRegistry | None = None) -> str:
    """Alias for :func:`build_provider_docs`."""
    return build_provider_docs(registry)


def docs_path(root: Path | None = None) -> Path:
    """Return the path of the committed reference, ``docs/PROVIDERS.md``.

    Without an explicit *root*, the repository root is found by walking up from
    this module so the command works from any working directory. An installed
    wheel has no repository, so the current directory is used instead.
    """
    if root is not None:
        return Path(root) / "docs" / DOCS_FILENAME
    for parent in Path(__file__).resolve().parents:
        if (parent / "docs" / "DESIGN.md").is_file():
            return parent / "docs" / DOCS_FILENAME
    return Path.cwd() / "docs" / DOCS_FILENAME


def render_provider_docs(
    providers: Mapping[str, ProviderMeta] | Iterable[tuple[str, ProviderMeta]],
) -> str:
    """Render *providers* as stable Markdown text."""
    entries = _normalize(providers)

    lines = [
        f"# {DOCS_TITLE}",
        "",
        _GENERATED_NOTICE,
        _PREAMBLE,
        "",
        "## Capability matrix",
        "",
        "| Provider | Capabilities | Rate limit | Quality rank | License | "
        "Commercial use |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for name, metadata in entries.items():
        lines.append(
            "| "
            + " | ".join(
                (
                    _code(name),
                    _capabilities(metadata),
                    _rate_limit(metadata),
                    _quality_rank(metadata),
                    _license(metadata),
                    _commercial_use(metadata),
                )
            )
            + " |"
        )

    lines.extend(
        [
            "",
            "## Pricing",
            "",
            "| Provider | Capability | Price |",
            "| --- | --- | --- |",
        ]
    )
    for name, metadata in entries.items():
        if metadata.pricing:
            for capability in sorted(metadata.pricing):
                price = metadata.pricing[capability]
                lines.append(
                    f"| {_code(name)} | {_code(capability)} | {_price(price)} |"
                )
        else:
            lines.append(f"| {_code(name)} | - | - |")

    lines.extend(
        [
            "",
            "## Supported options",
            "",
            "| Provider | Capability | Options |",
            "| --- | --- | --- |",
        ]
    )
    for name, metadata in entries.items():
        if metadata.supported_options:
            for capability in sorted(metadata.supported_options):
                options = ", ".join(
                    _code(option) for option in metadata.supported_options[capability]
                )
                lines.append(f"| {_code(name)} | {_code(capability)} | {options} |")
        else:
            lines.append(f"| {_code(name)} | - | - |")

    lines.extend(
        [
            "",
            "## Licensing",
            "",
            "| Provider | License | Commercial use | Attribution required | Notes |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for name, metadata in entries.items():
        notes = _cell(metadata.commercial_use_notes) or "-"
        attribution = "yes" if metadata.license.requires_attribution else "no"
        lines.append(
            f"| {_code(name)} | {_license(metadata)} | "
            f"{_commercial_use(metadata)} | {attribution} | {notes} |"
        )

    return "\n".join(lines).rstrip() + "\n"


def _normalize(
    providers: Mapping[str, ProviderMeta] | Iterable[tuple[str, ProviderMeta]],
) -> dict[str, ProviderMeta]:
    items = providers.items() if isinstance(providers, Mapping) else providers
    normalized = {str(name).strip(): metadata for name, metadata in items}
    return dict(sorted(normalized.items()))


def _cell(value: Any) -> str:
    return " ".join(str(value).split()).replace("|", "\\|")


def _code(value: Any) -> str:
    return f"`{_cell(value)}`"


def _capabilities(metadata: ProviderMeta) -> str:
    if not metadata.capabilities:
        return "-"
    return ", ".join(_code(capability) for capability in metadata.capabilities)


def _rate_limit(metadata: ProviderMeta) -> str:
    limit = metadata.rate_limit
    if limit.is_unlimited:
        return "unlimited"
    parts = [f"{limit.requests_per_minute}/min"]
    if limit.burst:
        parts.append(f"burst {limit.burst}")
    if limit.max_concurrency:
        parts.append(f"concurrency {limit.max_concurrency}")
    return ", ".join(parts)


def _quality_rank(metadata: ProviderMeta) -> str:
    return "-" if metadata.quality_rank is None else str(metadata.quality_rank)


def _commercial_use(metadata: ProviderMeta) -> str:
    value = metadata.license.commercial_use
    if value is None:
        return "unknown"
    return "yes" if value else "no"


def _license(metadata: ProviderMeta) -> str:
    license_ = metadata.license
    name = _cell(license_.name)
    url = _cell(license_.url)
    if name and url:
        return f"{name} ([terms]({url}))"
    if name:
        return name
    if url:
        return f"[terms]({url})"
    return "-"


def _amount(value: float) -> str:
    text = f"{value:.12f}".rstrip("0").rstrip(".")
    return text or "0"


def _price(price: ProviderPrice) -> str:
    amount = _amount(price.amount_usd)
    if price.currency.upper() == "USD":
        amount = f"${amount}"
    else:
        amount = f"{amount} {price.currency}"
    unit = _cell(price.unit)
    if price.units_per_price == 1:
        return f"{amount} per {unit}"
    return f"{amount} per {_amount(price.units_per_price)} {unit}"
