"""Deterministic Markdown matrix of the registered provider metadata.

The document is rendered from :class:`~aivia.core.models.provider.ProviderMeta`
values declared by the provider classes. Static metadata is read without
constructing an adapter, so generating the reference never touches the network
or spends money. The committed copy is compared byte for byte, which makes a
stale reference fail the test suite and therefore CI.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

