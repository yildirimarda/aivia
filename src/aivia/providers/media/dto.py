"""Canonical request and result DTOs for image, video, music and speech.

The capability protocols describe the vendor-facing shape of each media kind.
This module gives the media service one vocabulary across those kinds while
reusing the protocol models, so the service and an adapter cannot drift apart.
A request or result names its kind and carries exactly one payload whose type
must match that kind; the nested models own the field level range checks.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Self, cast

from pydantic import model_validator

from aivia.providers.protocols.base import ProtocolModel
from aivia.providers.protocols.image import ImageRequest, ImageResult
from aivia.providers.protocols.music import MusicRequest, MusicTrack
from aivia.providers.protocols.tts import TTSRequest, TTSResponse
from aivia.providers.protocols.video import VideoRequest, VideoResult

__all__ = [
    "ImageRequest",
    "ImageResult",
    "MediaKind",
    "MediaRequest",
    "MediaResult",
    "MusicRequest",
    "MusicResult",
    "SpeechRequest",
    "SpeechResult",
    "VideoRequest",
    "VideoResult",
]

MusicResult = MusicTrack
"""The result of generating one music track."""

SpeechRequest = TTSRequest
"""The request to synthesize one speech payload."""

SpeechResult = TTSResponse
"""The result of synthesizing one speech payload."""

_REQUEST_FIELDS = ("image", "video", "music", "speech")
_RESULT_FIELDS = ("image", "video", "music", "speech")


class MediaKind(StrEnum):
    """The kind of media a request or result describes."""

    IMAGE = "image"
    VIDEO = "video"
    MUSIC = "music"
    SPEECH = "speech"


def _validate_payload(kind: MediaKind, fields: tuple[str, ...], model: object) -> None:
    present = [name for name in fields if getattr(model, name) is not None]
    if len(present) != 1:
        raise ValueError(
            "media model needs exactly one of " + ", ".join(fields) + " payload"
        )
    if present[0] != kind.value:
        raise ValueError(
            f"media kind {kind.value!r} does not match the {present[0]!r} payload"
        )


class MediaRequest(ProtocolModel):
    """A service-level media request with exactly one kind-specific payload.

    ``kind`` selects which of ``image``, ``video``, ``music`` or ``speech`` is
    set. The payload keeps the full range validation of its protocol request,
    and this model rejects a missing payload, a second payload or a payload
    that does not match ``kind``.
    """

    kind: MediaKind
    image: ImageRequest | None = None
    video: VideoRequest | None = None
    music: MusicRequest | None = None
    speech: SpeechRequest | None = None

    @model_validator(mode="after")
    def _validate_kind(self) -> Self:
        _validate_payload(self.kind, _REQUEST_FIELDS, self)
        return self

    @property
    def payload(self) -> ImageRequest | VideoRequest | MusicRequest | SpeechRequest:
        """The request selected by :attr:`kind`."""
        return cast(
            "ImageRequest | VideoRequest | MusicRequest | SpeechRequest",
            getattr(self, self.kind.value),
        )

    @classmethod
    def for_image(cls, request: ImageRequest) -> MediaRequest:
        """Wrap an image request."""
        return cls(kind=MediaKind.IMAGE, image=request)

    @classmethod
    def for_video(cls, request: VideoRequest) -> MediaRequest:
        """Wrap a video request."""
        return cls(kind=MediaKind.VIDEO, video=request)

    @classmethod
    def for_music(cls, request: MusicRequest) -> MediaRequest:
        """Wrap a music request."""
        return cls(kind=MediaKind.MUSIC, music=request)

    @classmethod
    def for_speech(cls, request: SpeechRequest) -> MediaRequest:
        """Wrap a speech request."""
        return cls(kind=MediaKind.SPEECH, speech=request)


class MediaResult(ProtocolModel):
    """A service-level media result with exactly one kind-specific payload.

    ``kind`` selects which of ``image``, ``video``, ``music`` or ``speech`` is
    set. Each payload keeps the validation of its protocol result, including
    the rule that generated bytes and a remote URL are mutually exclusive.
    """

    kind: MediaKind
    image: ImageResult | None = None
    video: VideoResult | None = None
    music: MusicResult | None = None
    speech: SpeechResult | None = None

    @model_validator(mode="after")
    def _validate_kind(self) -> Self:
        _validate_payload(self.kind, _RESULT_FIELDS, self)
        return self

    @property
    def payload(self) -> ImageResult | VideoResult | MusicResult | SpeechResult:
        """The result selected by :attr:`kind`."""
        return cast(
            "ImageResult | VideoResult | MusicResult | SpeechResult",
            getattr(self, self.kind.value),
        )

    @classmethod
    def for_image(cls, result: ImageResult) -> MediaResult:
        """Wrap an image result."""
        return cls(kind=MediaKind.IMAGE, image=result)

    @classmethod
    def for_video(cls, result: VideoResult) -> MediaResult:
        """Wrap a video result."""
        return cls(kind=MediaKind.VIDEO, video=result)

    @classmethod
    def for_music(cls, result: MusicResult) -> MediaResult:
        """Wrap a music result."""
        return cls(kind=MediaKind.MUSIC, music=result)

    @classmethod
    def for_speech(cls, result: SpeechResult) -> MediaResult:
        """Wrap a speech result."""
        return cls(kind=MediaKind.SPEECH, speech=result)
