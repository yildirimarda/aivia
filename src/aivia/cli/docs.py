"""Deterministic Markdown reference for the registered CLI commands.

The document is rendered from the command registry: every registered subcommand
appears with its help text and the arguments its parser accepts, so the
reference cannot drift from the registry. The committed copy is compared byte
for byte, which makes a stale reference fail the test suite.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from aivia.cli.globals import build_global_parser
from aivia.cli.registry import Command, CommandRegistry, register_command
from aivia.cli.registry import registry as default_registry

__all__ = [
    "DOCS_FILENAME",
    "DOCS_TITLE",
    "build_cli_docs",
    "configure",
    "docs_path",
    "dump_cli_docs",
    "render_cli_docs",
    "run_docs",
]

DOCS_FILENAME = "CLI.md"
DOCS_TITLE = "AIVIA command line reference"

_GENERATED_NOTICE = (
    "<!-- Generated by `aivia docs`; do not edit by hand. -->\n"
    "<!-- Regenerate: aivia docs --output docs/CLI.md -->\n"
)

_PREAMBLE = (
    "This reference is generated from the registered command registry. Every "
    "registered subcommand is one section, listed in sorted order with its help "
    "text and the arguments its parser accepts. The committed copy is compared "
    "byte for byte, so a stale reference fails CI."
)


def build_cli_docs(registry: CommandRegistry | None = None) -> str:
    """Return the Markdown reference for every command in *registry*."""
    active = registry if registry is not None else default_registry
    return render_cli_docs(active)


def dump_cli_docs(registry: CommandRegistry | None = None) -> str:
    """Alias for :func:`build_cli_docs`, mirroring ``dump_config_docs``."""
    return build_cli_docs(registry)


def docs_path(root: Path | None = None) -> Path:
    """Return the path of the committed reference, ``docs/CLI.md``.

    Without an explicit *root*, the repository root is found by walking up from
    this module so the command works from any working directory. An installed
    wheel has no repository, so the current directory is used instead.
    """
    if root is not None:
        return Path(root) / "docs" / DOCS_FILENAME
    for parent in Path(__file__).resolve().parents:
        if (parent / "docs" / "DESIGN.md").is_file():
            return parent / "docs" / DOCS_FILENAME
    return Path.cwd() / "docs" / DOCS_FILENAME


def render_cli_docs(registry: CommandRegistry) -> str:
    """Render *registry* as stable Markdown text."""
    global_options = _global_option_strings()
    lines = [
        f"# {DOCS_TITLE}",
        "",
        _GENERATED_NOTICE,
        _PREAMBLE,
        "",
        "## Commands",
        "",
        "| Command | Help |",
        "| --- | --- |",
    ]
    commands = list(registry)
    for command in commands:
        help_line = (command.help or "").splitlines()[0]
        lines.append(f"| `{command.name}` | {_cell(help_line)} |")
    lines.extend(["", "## Global options", ""])
    lines.extend(_global_option_rows())
    for command in commands:
        lines.extend(_render_command(command, global_options))
    return "\n".join(lines).rstrip() + "\n"


def _global_option_rows() -> list[str]:
    rows: list[tuple[str, str, str, str]] = []
    for action in build_global_parser()._actions:
        option_strings = action.option_strings
        if not option_strings:
            continue
        rows.append(_argument_row(action))
    rows.sort(key=lambda row: row[0])
    lines = [
        "| Flag | Type | Default | Description |",
        "| --- | --- | --- | --- |",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    lines.append("")
    return lines


def _global_option_strings() -> set[str]:
    strings: set[str] = set()
    for action in build_global_parser()._actions:
        strings.update(action.option_strings)
    return strings


def _command_parser(command: Command) -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog=f"aivia {command.name}", add_help=False)
    subparsers = parser.add_subparsers()
    return command.add_parser(subparsers)


def _render_command(command: Command, global_option_strings: set[str]) -> list[str]:
    parser = _command_parser(command)
    lines = [f"## `{command.name}`", ""]
    if command.help:
        lines.extend([_cell(command.help), ""])
    rows: list[tuple[str, str, str, str]] = []
    for action in parser._actions:
        option_strings = action.option_strings
        if not option_strings or option_strings == ["-h", "--help"]:
            continue
        if any(option in global_option_strings for option in option_strings):
            continue
        rows.append(_argument_row(action))
    rows.sort(key=lambda row: row[0])
    if rows:
        lines.extend(
            [
                "| Flag | Type | Default | Description |",
                "| --- | --- | --- | --- |",
            ]
        )
        lines.extend("| " + " | ".join(row) + " |" for row in rows)
    else:
        lines.append("No arguments.")
    lines.append("")
    return lines


def _argument_row(
    action: argparse.Action,
) -> tuple[str, str, str, str]:
    option_strings = action.option_strings
    flag = ", ".join(f"`{option}`" for option in option_strings)
    return (
        flag,
        _argument_type(action),
        _argument_default(action),
        _cell(action.help or ""),
    )


def _argument_type(action: argparse.Action) -> str:
    if action.choices:
        choices = ", ".join(f"`{choice}`" for choice in sorted(action.choices))
        return f"one of: {choices}"
    if action.type is not None:
        name = getattr(action.type, "__name__", None) or ""
        return {"int": "integer", "float": "number"}.get(name, name or "any")
    if action.nargs == 0 or action.const is not None:
        return "boolean"
    return "string"


def _argument_default(action: argparse.Action) -> str:
    default = action.default
    if default is argparse.SUPPRESS or default is None:
        return "—"
    if isinstance(default, bool):
        return "`true`" if default else "`false`"
    if isinstance(default, (list, tuple, set)):
        values = ", ".join(f"`{value}`" for value in sorted(default))
        return values or "—"
    return f"`{_cell(str(default))}`"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def configure(parser: argparse.ArgumentParser) -> None:
    """Add the ``--output`` and ``--check`` flags to the docs command."""
    parser.add_argument(
        "--output",
        metavar="PATH",
        help="write the reference to PATH instead of standard output",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the reference at PATH (or docs/CLI.md) is stale",
    )
    parser.set_defaults(_cli_docs_handler=run_docs)


def run_docs(args: argparse.Namespace) -> int:
    """Print, write or check the generated CLI reference."""
    text = dump_cli_docs()
    target = Path(args.output) if args.output is not None else docs_path()
    if args.check:
        try:
            existing = target.read_text(encoding="utf-8")
        except OSError:
            existing = None
        if existing != text:
            print(f"error: CLI reference is stale: {target}", file=sys.stderr)
            print(
                f"regenerate it with: aivia docs --output {target}",
                file=sys.stderr,
            )
            return 1
        print(f"CLI reference is up to date: {target}")
        return 0
    if args.output is None:
        print(text, end="")
        return 0
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    except OSError as exc:
        print(f"error: cannot write {target}: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {target}")
    return 0


register_command(
    "docs",
    run_docs,
    help="Generate the command line reference",
    configure=configure,
)
